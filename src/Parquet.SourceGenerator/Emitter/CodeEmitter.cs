            "            await ValidateReaderAsync(probe, probeStream, options, cancellationToken).ConfigureAwait(false);"
        );
        RowGroupLayoutComponent.EmitIndexedLayoutProbe(
            builder,
            "probe",
            "rowGroupCount",
            "rowOffsets",
            "totalRows",
            "maxRowGroupSize",
            declareVariables: false,
            indent: "            ",
            optionsVar: "options"
        );
        builder.AppendLine("            }");
        builder.AppendLine("            finally");
        builder.AppendLine("            {");
        builder.AppendLine("                await probe.DisposeAsync().ConfigureAwait(false);");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine(
            $"        if (rowGroupCount == 0) return global::System.Array.Empty<{model.ClassName}>();"
        );
        builder.AppendLine();
        builder.AppendLine(
            "        // Small row count or single row group fast path: drop to sequential reader"
        );
        builder.AppendLine("        if (rowGroupCount <= 1 || totalRows <= 10_000)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            return await ReadBufferSequentialArrayAsync(sourceBytes, options, cancellationToken).ConfigureAwait(false);"
        );
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine($"        var resultArray = new {model.ClassName}[totalRows];");
        builder.AppendLine(
            "        using var linkedCts = global::System.Threading.CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);"
        );
        builder.AppendLine("        var workerToken = linkedCts.Token;");
        builder.AppendLine("        var cursor = new int[1];");
        builder.AppendLine();
        builder.AppendLine(
            "        int requested = options.MaxDegreeOfParallelism > 0 ? options.MaxDegreeOfParallelism : global::System.Environment.ProcessorCount;"
        );
        builder.AppendLine(
            "        int workerCount = requested < rowGroupCount ? requested : rowGroupCount;"
        );
        builder.AppendLine("        if (workerCount < 1) workerCount = 1;");
        builder.AppendLine();
        builder.AppendLine("        if (workerCount == 1)");
        builder.AppendLine("        {");
        builder.AppendLine("            await ReadRowGroupsIntoAsync(sourceBytes,");
        builder.AppendLine("                formatOptions,");
        builder.AppendLine("                resultArray,");
        builder.AppendLine("                rowOffsets,");
        builder.AppendLine("                cursor,");
        builder.AppendLine("                rowGroupCount,");
        builder.AppendLine("                maxRowGroupSize,");
        builder.AppendLine("                options,");
        builder.AppendLine("                linkedCts,");
        builder.AppendLine("                workerToken).ConfigureAwait(false);");
        builder.AppendLine("        }");
        builder.AppendLine("        else");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            var workers = new global::System.Threading.Tasks.Task[workerCount];"
        );
        builder.AppendLine("            for (int w = 0; w < workerCount; w++)");
        builder.AppendLine("            {");
        builder.AppendLine("                workers[w] = global::System.Threading.Tasks.Task.Run(");
        builder.AppendLine("                    () => ReadRowGroupsIntoAsync(sourceBytes,");
        builder.AppendLine("                        formatOptions,");
        builder.AppendLine("                        resultArray,");
        builder.AppendLine("                        rowOffsets,");
        builder.AppendLine("                        cursor,");
        builder.AppendLine("                        rowGroupCount,");
        builder.AppendLine("                        maxRowGroupSize,");
        builder.AppendLine("                        options,");
        builder.AppendLine("                        linkedCts,");
        builder.AppendLine("                        workerToken),");
        builder.AppendLine("                    workerToken);");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            try");
        builder.AppendLine("            {");
        builder.AppendLine(
            "                await global::System.Threading.Tasks.Task.WhenAll(workers).ConfigureAwait(false);"
        );
        builder.AppendLine("            }");
        builder.AppendLine("            catch");
        builder.AppendLine("            {");
        builder.AppendLine("                await linkedCts.CancelAsync().ConfigureAwait(false);");
        builder.AppendLine("                throw;");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return resultArray;");
        builder.AppendLine("    }");
        builder.AppendLine();

        EmitReadRowGroupsIntoAsync(builder, model);
    }

    private static void EmitReadRowGroupsIntoAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// One parallel-read worker: opens its own reader over the shared buffer and materialises every"
        );
        builder.AppendLine("    /// row group it manages to claim.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <remarks>");
        builder.AppendLine(
            "    /// Workers write into disjoint index ranges of <paramref name=\"target\"/> — a row group's rows"
        );
        builder.AppendLine(
            "    /// start at its precomputed offset — so no synchronisation is needed beyond claiming the group."
        );
        builder.AppendLine("    /// </remarks>");
        builder.AppendLine(
            "    private static async global::System.Threading.Tasks.Task ReadRowGroupsIntoAsync("
        );
        builder.AppendLine("        global::System.ReadOnlyMemory<byte> parquetBytes,");
        builder.AppendLine("        global::Parquet.ParquetOptions formatOptions,");
        builder.AppendLine($"        {model.ClassName}[] target,");
        builder.AppendLine("        int[] rowOffsets,");
        builder.AppendLine("        int[] cursor,");
        builder.AppendLine("        int rowGroupCount,");
        builder.AppendLine("        int maxRowGroupSize,");
        builder.AppendLine(
            "        global::Parquet.SourceGenerator.ParquetSerializerOptions options,"
        );
        builder.AppendLine("        global::System.Threading.CancellationTokenSource linkedCts,");
        builder.AppendLine("        global::System.Threading.CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        try");
        builder.AppendLine("        {");
        if (StringDeduplicatorComponent.HasStringProperties(model))
        {
            builder.AppendLine("            bool deduplicateStrings = options.DeduplicateStrings;");
        }
        builder.AppendLine("            using var stream = CreateBufferStream(parquetBytes);");
        builder.AppendLine(
            "            using var guardedStream = CreateGuardedReadStream(stream, options);"
        );
        builder.AppendLine(
            "            var reader = await global::Parquet.ParquetReader.CreateAsync("
        );
        builder.AppendLine("                guardedStream,");
        builder.AppendLine("                formatOptions,");
        builder.AppendLine(
            "                cancellationToken: cancellationToken).ConfigureAwait(false);"
        );
        // try/finally instead of an `await using` scope: ConfigureAwait on an IAsyncDisposable needs ConfiguredAsyncDisposable, and these methods sit at the CA1506 ceiling.
        builder.AppendLine("            try");
        builder.AppendLine("            {");
        builder.AppendLine("            guardedStream.Activate();");
        builder.AppendLine(
            "            await ValidateReaderAsync(reader, stream, options, cancellationToken).ConfigureAwait(false);"
        );
        builder.AppendLine();
        builder.AppendLine("            var fileFields = reader.Schema.DataFields;");
        builder.AppendLine();

        if (model.Properties.Length > 0)
        {
            builder.AppendLine(
                "            global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? fieldsByName = null;"
            );
            foreach (LeafColumn col in EmissionPlan.For(model).Columns)
            {
                builder.AppendLine(EmitResolveFieldLine(col, "            "));
            }
            builder.AppendLine();
        }

        EmitRentalsFor(builder, model, "maxRowGroupSize", indent: "            ");
        builder.AppendLine();
        builder.AppendLine("            try");
        builder.AppendLine("            {");
        if (StringDeduplicatorComponent.HasStringProperties(model))
        {
            builder.AppendLine(
                "                using var stringDeduplicator = new StringDeduplicator(512);"
            );
            builder.AppendLine();
        }
        builder.AppendLine("                while (true)");
        builder.AppendLine("                {");
        builder.AppendLine(
            "                    int r = global::System.Threading.Interlocked.Increment(ref cursor[0]) - 1;"
        );
        builder.AppendLine("                    if (r >= rowGroupCount) break;");
        builder.AppendLine();
        builder.AppendLine("                    cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine(
            "                    using var groupReader = reader.OpenRowGroupReader(r);"
        );
        builder.AppendLine(
            "                    int rowCount = checked((int)groupReader.RowCount);"
        );
        builder.AppendLine(
            "                    if (rowCount < 0 || rowCount > options.MaxAllocationValues)"
        );
        builder.AppendLine("                    {");
        builder.AppendLine(
            "                        throw new global::System.IO.InvalidDataException($\"Row group {r} row count {rowCount} is invalid or exceeds maximum allowed {options.MaxAllocationValues}.\");"
        );
        builder.AppendLine("                    }");
        builder.AppendLine("                    int startIdx = rowOffsets[r];");
        builder.AppendLine();
        foreach (LeafColumn col in EmissionPlan.For(model).Columns)
        {
            EmitReadWithNullBypass(
                builder,
                col,
                $"field_{col.Slot}",
                $"buffer_{col.Slot}",
                indent: "                    "
            );
        }
        builder.AppendLine();
        EmitArrayMaterializationFor(
            builder,
            model,
            "target",
            "startIdx",
            indent: "                    "
        );
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine("            finally");
        builder.AppendLine("            {");
        EmitReturnsFor(builder, model, indent: "                ");
        builder.AppendLine("            }");
        builder.AppendLine("            }");
        builder.AppendLine("            finally");
        builder.AppendLine("            {");
        builder.AppendLine("                await reader.DisposeAsync().ConfigureAwait(false);");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        catch");
        builder.AppendLine("        {");
        builder.AppendLine("            await linkedCts.CancelAsync().ConfigureAwait(false);");
        builder.AppendLine("            throw;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

