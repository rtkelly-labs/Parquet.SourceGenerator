    /// <summary>
    /// Emits a bounds-check-free extraction loop over a contiguous source (List span or array):
    /// all source and destination element accesses go through Unsafe.Add on raw refs obtained
    /// before the loop, so the JIT executes zero per-iteration bounds checks (issue #144).
    /// </summary>
    private static void EmitUnboundExtractionLoop(
        StringBuilder builder,
        TargetClassModel model,
        string sourceExpr,
        bool sourceIsArray = false
    )
    {
        string indent = "                    ";
        string srcRefDecl = sourceIsArray
            ? $"ref var srcRef_ = ref global::System.Runtime.InteropServices.MemoryMarshal.GetArrayDataReference({sourceExpr});"
            : $"ref var srcRef_ = ref global::System.Runtime.InteropServices.MemoryMarshal.GetReference({sourceExpr});";
        builder.AppendLine($"{indent}{srcRefDecl}");

        foreach (LeafColumn col in EmissionPlan.For(model).Columns)
        {
            if (col.IsCompound || col.IsListLeaf)
                continue; // compound/list leaves use plain array indexing (branchy ladder anyway)
            int i = col.Slot;
            PropertyModel prop = col.Leaf;
            builder.AppendLine(
                $"{indent}ref var dstRef_{i} = ref global::System.Runtime.InteropServices.MemoryMarshal.GetArrayDataReference(buffer_{i});"
            );
            if (BufferPoolComponent.UsesWriteAllParts(prop))
            {
                builder.AppendLine(
                    $"{indent}ref var defRef_{i} = ref global::System.Runtime.InteropServices.MemoryMarshal.GetArrayDataReference(defLevels_{i});"
                );
            }
        }

        builder.AppendLine($"{indent}for (int i = 0; i < count; i++)");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine(
            $"{indent}    ref readonly var item = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref srcRef_, i);"
        );
        EmitUnboundPropertyAssignments(builder, model, indent + "    ");
        builder.AppendLine($"{indent}}}");
    }

    private static void EmitUnboundPropertyAssignments(
        StringBuilder builder,
        TargetClassModel model,
        string prefix
    )
    {
        foreach (LeafColumn col in EmissionPlan.For(model).Columns)
        {
            int i = col.Slot;
            PropertyModel prop = col.Leaf;
            if (col.IsListLeaf)
            {
                CompoundMapping.EmitListExtraction(builder, col, "item", prefix);
                continue;
            }
            if (col.IsCompound)
            {
                CompoundMapping.EmitCompoundExtraction(builder, col, "item", "i", prefix);
                continue;
            }
            if (BufferPoolComponent.UsesWriteAllParts(prop))
            {
                // Branchless definition-level extraction and value compaction (issue #145):
                // the presence flag is read as a byte with no conditional jump, the payload is
                // stored unconditionally at the current compaction cursor (a null's write is
                // overwritten by the next non-null, and the cursor never leaves the buffer
                // because nonNullCount <= i < count <= buffer.Length), and the cursor advances
                // by the flag. No unpredictable branch remains in the hot loop.
                string valVar = $"val_{i}";
                string hasVar = $"has_{i}";
                string flagVar = $"hv_{i}";
                builder.AppendLine($"{prefix}var {valVar} = item.{prop.Name};");
                builder.AppendLine($"{prefix}bool {hasVar} = {valVar}.HasValue;");
                builder.AppendLine(
                    $"{prefix}int {flagVar} = global::System.Runtime.CompilerServices.Unsafe.As<bool, byte>(ref {hasVar});"
                );
                builder.AppendLine(
                    $"{prefix}global::System.Runtime.CompilerServices.Unsafe.Add(ref dstRef_{i}, nonNullCount_{i}) = {GetBranchlessNonNullExpression(prop, valVar)};"
                );
                builder.AppendLine($"{prefix}nonNullCount_{i} += {flagVar};");
                builder.AppendLine(
                    $"{prefix}global::System.Runtime.CompilerServices.Unsafe.Add(ref defRef_{i}, i) = {flagVar};"
                );
            }
            else
            {
                string writeExpr = GetWriteExpression(prop, $"item.{prop.Name}");
                builder.AppendLine(
                    $"{prefix}global::System.Runtime.CompilerServices.Unsafe.Add(ref dstRef_{i}, i) = {writeExpr};"
                );
            }
        }
    }

