    private static void EmitValidateReader(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Validates the ParquetReader against configured defensive security bounds."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    private static async global::System.Threading.Tasks.Task ValidateReaderAsync("
        );
        builder.AppendLine("        global::Parquet.ParquetReader reader,");
        builder.AppendLine("        global::System.IO.Stream stream,");
        builder.AppendLine(
            "        global::Parquet.SourceGenerator.ParquetSerializerOptions options,"
        );
        builder.AppendLine("        global::System.Threading.CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        int rowGroupCount = reader.RowGroupCount;");
        builder.AppendLine(
            "        if (rowGroupCount < 0 || rowGroupCount > options.MaxRowGroupCount)"
        );
        builder.AppendLine("        {");
        builder.AppendLine(
            "            throw new global::System.IO.InvalidDataException($\"Row group count {rowGroupCount} is invalid or exceeds maximum allowed {options.MaxRowGroupCount}.\");"
        );
        builder.AppendLine("        }");
        builder.AppendLine(
            "        long footerStart = await GetFooterStartAsync(stream, cancellationToken).ConfigureAwait(false);"
        );
        builder.AppendLine("        ValidateColumnChunkBounds(reader, footerStart, 1_000_000);");
        builder.AppendLine("        int maxDepth = 0;");
        builder.AppendLine("        foreach (var field in reader.Schema.Fields)");
        builder.AppendLine("        {");
        builder.AppendLine("            int d = GetFieldDepth(field);");
        builder.AppendLine("            if (d > maxDepth) maxDepth = d;");
        builder.AppendLine("        }");
        builder.AppendLine("        if (maxDepth > options.MaxNestingDepth)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            throw new global::System.IO.InvalidDataException($\"Schema nesting depth {maxDepth} exceeds maximum allowed {options.MaxNestingDepth}.\");"
        );
        builder.AppendLine("        }");
        if (model.Properties.Length > 0)
        {
            builder.AppendLine();
            builder.AppendLine(
                "        var fileFieldsForTypeValidation = reader.Schema.DataFields;"
            );
            foreach (LeafColumn col in EmissionPlan.For(model).Columns)
            {
                builder.AppendLine(
                    $"        ValidatePhysicalType(reader, fileFieldsForTypeValidation, _field_{col.Slot});"
                );
            }
        }
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine(
            "    private static int GetFieldDepth(global::Parquet.Schema.Field field)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        if (field is global::Parquet.Schema.StructField sf)");
        builder.AppendLine("        {");
        builder.AppendLine("            int max = 0;");
        builder.AppendLine("            foreach (var child in sf.Fields)");
        builder.AppendLine("            {");
        builder.AppendLine("                int d = GetFieldDepth(child);");
        builder.AppendLine("                if (d > max) max = d;");
        builder.AppendLine("            }");
        builder.AppendLine("            return 1 + max;");
        builder.AppendLine("        }");
        builder.AppendLine("        if (field is global::Parquet.Schema.ListField lf)");
        builder.AppendLine("        {");
        builder.AppendLine("            return 1 + GetFieldDepth(lf.Item);");
        builder.AppendLine("        }");
        builder.AppendLine("        if (field is global::Parquet.Schema.MapField mf)");
        builder.AppendLine("        {");
        builder.AppendLine("            int keyDepth = GetFieldDepth(mf.Key);");
        builder.AppendLine("            int valueDepth = GetFieldDepth(mf.Value);");
        builder.AppendLine(
            "            return 1 + (keyDepth > valueDepth ? keyDepth : valueDepth);"
        );
        builder.AppendLine("        }");
        builder.AppendLine("        return 1;");
        builder.AppendLine("    }");
    }

    private static string GetWritePrimitiveCall(
        LeafColumn col,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        if (col.IsListLeaf)
        {
            // List lane: values + def + rep arrays sized by written entries (docs/15 §1.2).
            string packedL = col.PackedType;
            return $"{indent}await groupWriter.WriteAllPartsAsync<{packedL}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{packedL}>({bufName}, 0, nonNullCount_{col.Slot}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{col.Slot}, 0, posCount_{col.Slot}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(repLevels_{col.Slot}, 0, posCount_{col.Slot}),\n"
                + $"{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (col.IsCompound)
        {
            // Compound-path leaf: packed values plus a definition ladder; the group's own
            // optionality means even a non-nullable leaf needs levels (docs/15 §1).
            string packed = col.PackedType;
            return $"{indent}await groupWriter.WriteAllPartsAsync<{packed}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{packed}>({bufName}, 0, nonNullCount_{col.Slot}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{col.Slot}, 0, count),\n"
                + $"{indent}    null,\n"
                + $"{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        PropertyModel prop = col.Leaf;
        int propIndex = col.Slot;
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (BufferPoolComponent.UsesWriteAllParts(prop))
        {
            string nonNullType = BufferPoolComponent.GetNonNullableBufferType(prop);
            return $"{indent}await groupWriter.WriteAllPartsAsync<{nonNullType}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{nonNullType}>({bufName}, 0, nonNullCount_{propIndex}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{propIndex}, 0, count),\n"
                + $"{indent}    null,\n"
                + $"{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }
        if (isString)
        {
            string memType = prop.IsNullable
                ? "global::System.ReadOnlyMemory<char>?"
                : "global::System.ReadOnlyMemory<char>";
            return $"{indent}await groupWriter.WriteAsync<global::System.ReadOnlyMemory<char>>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (isByteArray)
        {
            string memType = prop.IsNullable
                ? "global::System.ReadOnlyMemory<byte>?"
                : "global::System.ReadOnlyMemory<byte>";
            return $"{indent}await groupWriter.WriteAsync<global::System.ReadOnlyMemory<byte>>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (prop.Kind == PropertyKind.Guid)
        {
            return $"{indent}await groupWriter.WriteAsync<global::System.Guid>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<global::System.Guid>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (prop.Kind == PropertyKind.DateOnly)
        {
            string memType = prop.IsNullable
                ? "global::System.DateTime?"
                : "global::System.DateTime";
            return $"{indent}await groupWriter.WriteAsync<global::System.DateTime>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            return $"{indent}await groupWriter.WriteAsync<{underlying}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{underlying}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (prop.Kind == PropertyKind.TimeSpan)
        {
            string memType = prop.IsNullable ? "int?" : "int";
            return $"{indent}await groupWriter.WriteAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        if (prop.Kind == PropertyKind.TimeOnly)
        {
            string memType = prop.IsNullable ? "long?" : "long";
            return $"{indent}await groupWriter.WriteAsync<long>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        string structType = prop.TypeName.TrimEnd('?');
        return $"{indent}await groupWriter.WriteAsync<{structType}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{structType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
    }

    /// <summary>
    /// Emits a column read, gated on the column-chunk NullCount statistic (issue #150).
    /// For nullable columns whose entire chunk is null, the data pages are never opened:
    /// the rented buffer is zeroed instead, skipping I/O, decompression and decoding.
    /// Columns without statistics (or partial nulls) fall through to the standard read.
    /// </summary>
    /// <summary>
    /// True when this column may legitimately be absent from a file the generated reader is asked
    /// to read: an optional flat column, which schema evolution allows a producer to drop.
    /// Required columns cannot be missing (resolution throws) and nested leaves are outside the
    /// documented compatibility envelope.
    /// </summary>
    private static bool SupportsMissingColumn(LeafColumn col) =>
        !col.IsCompound && !col.IsListLeaf && col.Leaf.IsNullable;

    /// <summary>
    /// Emits the one-line schema resolution for a column. Columns that can go missing capture the
    /// absence flag; the rest discard it, because for them resolution either succeeds or throws.
    /// </summary>
    internal static string EmitResolveFieldLine(LeafColumn col, string indent)
    {
        string missingArg = SupportsMissingColumn(col) ? $"out bool missing_{col.Slot}" : "out _";
        return $"{indent}var field_{col.Slot} = ResolveSchemaField(fileFields, {col.Slot}, _field_{col.Slot}, ref fieldsByName, {missingArg});";
    }

    /// <summary>
    /// Emits a column read. Every per-column guard is a call to a shared helper (see
    /// <see cref="ColumnHelpersComponent"/>), so the statements emitted here add no branches to
    /// the enclosing method however many columns the model has (#552).
    /// </summary>
    internal static void EmitReadWithNullBypass(
        StringBuilder builder,
        LeafColumn col,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        string missingArg = SupportsMissingColumn(col) ? $", missing_{col.Slot}" : "";
        builder.AppendLine(
            $"{indent}ValidateDictionaryEntryLimit(groupReader, stream, {fieldAccess}, \"{col.Leaf.Name}\", options{missingArg});"
        );

        if (col.IsListLeaf)
        {
            // Entries run ahead of rowCount for multi-element lists (docs/15 section 2.3).
            string packedL = col.PackedType;
            builder.AppendLine(
                $"{indent}var entries_{col.Slot} = PrepareListLeafBuffers<{packedL}>(groupReader, {fieldAccess}, \"{col.Leaf.Name}\", options, ref buffer_{col.Slot}, ref defLevels_{col.Slot}, ref repLevels_{col.Slot});"
            );
            builder.AppendLine($"{indent}await groupReader.ReadRawAsync<{packedL}>(");
            builder.AppendLine($"{indent}    {fieldAccess},");
            builder.AppendLine(
                $"{indent}    new global::System.Memory<{packedL}>({bufName}, 0, entries_{col.Slot}),"
            );
            builder.AppendLine(
                $"{indent}    new global::System.Memory<int>(defLevels_{col.Slot}, 0, entries_{col.Slot}),"
            );
            builder.AppendLine(
                $"{indent}    new global::System.Memory<int>(repLevels_{col.Slot}, 0, entries_{col.Slot}),"
            );
            builder.AppendLine($"{indent}    cancellationToken).ConfigureAwait(false);");
            EmitPackedStringLengthValidation(
                builder,
                col,
                bufName,
                indent,
                entriesVariable: $"entries_{col.Slot}"
            );
            return;
        }

        if (col.IsCompound)
        {
            // Struct-path leaves always carry a definition ladder — read raw with levels.
            // Entries == rowCount for structs (maxRep 0), so rowCount sizes everything.
            string packed = col.PackedType;
            builder.AppendLine($"{indent}await groupReader.ReadRawAsync<{packed}>(");
            builder.AppendLine($"{indent}    {fieldAccess},");
            builder.AppendLine(
                $"{indent}    new global::System.Memory<{packed}>({bufName}, 0, rowCount),"
            );
            builder.AppendLine(
                $"{indent}    new global::System.Memory<int>(defLevels_{col.Slot}, 0, rowCount),"
            );
            builder.AppendLine($"{indent}    null,");
            builder.AppendLine($"{indent}    cancellationToken).ConfigureAwait(false);");
            EmitPackedStringLengthValidation(
                builder,
                col,
                bufName,
                indent,
                entriesVariable: "rowCount"
            );
            return;
        }

        PropertyModel prop = col.Leaf;
        if (!prop.IsNullable)
        {
            builder.AppendLine(GetReadPrimitiveCall(prop, fieldAccess, bufName, indent));
            return;
        }

        builder.AppendLine(
            GetNullableReadCall(prop, fieldAccess, bufName, $"missing_{col.Slot}", indent)
        );
    }

    /// <summary>
    /// The packed-string UTF-8 length guard for a compound or list leaf, as one helper call.
    /// </summary>
    private static void EmitPackedStringLengthValidation(
        StringBuilder builder,
        LeafColumn col,
        string bufName,
        string indent,
        string entriesVariable
    )
    {
        if (
            col.Leaf.Kind != PropertyKind.Primitive
            || col.Leaf.TypeName.IndexOf("string", StringComparison.Ordinal) < 0
        )
        {
            return;
        }

        string columnName = col.IsListLeaf ? col.ListMemberName : col.Leaf.Name;
        builder.AppendLine(
            $"{indent}ValidatePackedStringLengths({bufName}, defLevels_{col.Slot}, {entriesVariable}, {col.MaxDef}, \"{col.Leaf.Name}\", \"{columnName}\", options);"
        );
    }

    /// <summary>
    /// The read for a nullable flat column: the shared helper decides whether the column is absent
    /// or entirely null (answer: nulls, no page read) and otherwise forwards to the normal read.
    /// </summary>
    private static string GetNullableReadCall(
        PropertyModel prop,
        string fieldAccess,
        string bufName,
        string missingVariable,
        string indent
    )
    {
        switch (ColumnHelpersComponent.GetNullableReadShape(prop))
        {
            case ColumnHelpersComponent.NullableReadShape.String:
                return $"{indent}await ReadNullableStringColumnAsync(\n{indent}    groupReader,\n{indent}    {fieldAccess},\n{indent}    {missingVariable},\n{indent}    {bufName},\n{indent}    rowCount,\n{indent}    deduplicateStrings,\n{indent}    stringDeduplicator,\n{indent}    options.MaxStringLengthBytes,\n{indent}    cancellationToken).ConfigureAwait(false);";
            case ColumnHelpersComponent.NullableReadShape.ByteArray:
                return $"{indent}await ReadNullableByteArrayColumnAsync(groupReader, {fieldAccess}, {missingVariable}, {bufName}, rowCount, cancellationToken).ConfigureAwait(false);";
            default:
                return $"{indent}await ReadNullableColumnAsync<{ColumnHelpersComponent.GetReadElementType(prop)}>(groupReader, {fieldAccess}, {missingVariable}, {bufName}, rowCount, cancellationToken).ConfigureAwait(false);";
        }
    }

    private static string GetReadPrimitiveCall(
        PropertyModel prop,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        if (prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string"))
        {
            // Every string uses the raw UTF-16 lane so the byte-length guard runs before any string
            // materialization, while the existing optional deduplication behavior is retained.
            return $"{indent}await ReadBoundedStringColumnAsync(\n{indent}    groupReader,\n{indent}    {fieldAccess},\n{indent}    {bufName},\n{indent}    rowCount,\n{indent}    deduplicateStrings,\n{indent}    stringDeduplicator,\n{indent}    options.MaxStringLengthBytes,\n{indent}    cancellationToken).ConfigureAwait(false);";
        }
        if (prop.Kind == PropertyKind.ByteArray)
        {
            return $"{indent}await groupReader.ReadAsync(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<byte[]?>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
        }

        string readType = ColumnHelpersComponent.GetReadElementType(prop);
        string memType = prop.IsNullable ? $"{readType}?" : readType;
        return $"{indent}await groupReader.ReadAsync<{readType}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken).ConfigureAwait(false);";
    }

