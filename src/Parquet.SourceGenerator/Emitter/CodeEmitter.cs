using System;
using System.Text;
using Parquet.SourceGenerator.Emitter.Columnar;
using Parquet.SourceGenerator.Emitter.Components;
using Parquet.SourceGenerator.Emitter.Compound;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Emitter;

/// <summary>
/// Emits high-performance C# extension classes targeting Parquet.Net v6 low-level primitives.
/// Features configurable ParquetSerializerOptions, IAsyncEnumerable streaming, compact 8-byte Int64 microsecond timestamp encoding,
/// parallel multi-row-group reading, zero-allocation Guid binary encoding, static pre-allocated DataFields,
/// O(1) index-check schema field resolution, ArrayPool buffer recycling, zero-copy ReadOnlyMemory overloads,
/// and Native AOT compatibility.
/// </summary>
public static class CodeEmitter
{
    /// <summary>
    /// Generates complete C# source code string for a given target model.
    /// </summary>
    public static string EmitSource(TargetClassModel model)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine(
            "#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8629"
        );
        builder.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        // For a nested target ("Outer.Inner") the dotted ClassName resolves in type positions but
        // cannot seed an identifier; the flattened form keeps sibling-nested types apart.
        string extensionsClassName =
            $"{model.ClassName.Replace(".", string.Empty)}ParquetExtensions";

        builder.AppendLine($"public static partial class {extensionsClassName}");
        builder.AppendLine("{");

        EmitSchema(builder, model);
        builder.AppendLine();

        EmitStaticFields(builder, model);
        builder.AppendLine();

        if (model.Properties.Length > 0)
        {
            EmitResolveSchemaField(builder, usePath: EmissionPlan.For(model).HasCompound);
            builder.AppendLine();
        }

        EmitFormatOptionsAndValidation(builder, model);
        builder.AppendLine();

        if (StringDeduplicatorComponent.HasStringProperties(model))
        {
            StringDeduplicatorComponent.EmitStringDeduplicator(builder);
            builder.AppendLine();
        }

        // Streaming row group writer — low level primitives, 100M+ scale, Native AOT compatible
        EmitWriteRowGroupAsync(builder, model);
        builder.AppendLine();

        // Direct columnar hand-off (#137) — caller already owns contiguous column buffers, so the
        // row transpose and its pooled rentals are skipped entirely. All-leaf models only.
        bool emitColumnar = ColumnarBatchComponent.IsSupported(model);
        if (emitColumnar)
        {
            ColumnarBatchComponent.EmitWriters(builder, model);
            builder.AppendLine();
        }

        // Primary write API — async (v6 requires async for writer creation)
        EmitWriteAsync(builder, model);
        builder.AppendLine();

        // Batched streaming write — splits IEnumerable into fixed-size row groups
        EmitWriteBatchedAsync(builder, model);
        builder.AppendLine();

        // IAsyncEnumerable streaming write
        EmitWriteAsyncEnumerable(builder, model);
        builder.AppendLine();

        // Read API — async (v6 low-level primitives)
        EmitReadAsync(builder, model);
        builder.AppendLine();

        // Direct array Read API — zero-copy array materialization
        EmitReadArrayAsync(builder, model);
        builder.AppendLine();

        // Parallel Read API — multi-core parallel object instantiation
        EmitReadParallelAsync(builder, model);
        builder.AppendLine();

        // Streaming Read API — IAsyncEnumerable streaming
        EmitReadStreamAsync(builder, model);
        builder.AppendLine();

        // Zero-copy ReadOnlyMemory overloads
        EmitReadMemoryOverloads(builder, model);

        // Struct-of-arrays columnar batch API (#147) — flat models only
        if (ColumnBatchComponent.Supports(model))
        {
            builder.AppendLine();
            ColumnBatchComponent.EmitBatchStruct(builder, model);
            builder.AppendLine();
            ColumnBatchComponent.EmitReadBatchesAsync(
                builder,
                model,
                static (b, col, field, buf) => EmitReadWithNullBypass(b, col, field, buf)
            );
        }

        // Row-group predicate pushdown (#149) — the zone-map guard the read loops call.
        if (RowGroupPruningComponent.IsEnabled(model))
        {
            builder.AppendLine();
            RowGroupPruningComponent.EmitAcceptRowGroup(builder, model);
        }

        // Sorted row-group pruning: binary search over footer [Min, Max] statistics (issue #151)
        var sortableColumns = SortedRowGroupPruningComponent.SortableColumns(model);
        if (sortableColumns.Count > 0)
        {
            builder.AppendLine();
            SortedRowGroupPruningComponent.EmitPruningHelpers(builder);
            builder.AppendLine();
            EmitReadPrunedRangeAsync(builder, model);
            SortedRowGroupPruningComponent.EmitLookupOverloads(builder, model, sortableColumns);
        }

        builder.AppendLine("}");

        RowGroupPruningComponent.EmitMetadataStruct(builder, model);
        if (emitColumnar)
        {
            builder.AppendLine();
            ColumnarBatchComponent.EmitBatchStruct(builder, model);
        }

        // Read entry point and builder structs (#217). Each axis of the read grid becomes a
        // member rather than a name segment; see docs/19-PUBLIC-API-SURFACE.md. The flat Read*
        // methods above remain and are what these delegate to, for one release (decision D3).
        ReadBuilderComponent.Emit(builder, model);

        return builder.ToString();
    }

    // ──────────────────────────────────────────────────────────
    //  SCHEMA & STATIC FIELD CACHING
    // ──────────────────────────────────────────────────────────

    private static void EmitSchema(StringBuilder builder, TargetClassModel model)
    {
        if (EmissionPlan.For(model).HasCompound)
        {
            CompoundSchema.EmitSchema(builder, model);
            return;
        }
        SchemaComponent.EmitSchema(builder, model);
    }

    private static void EmitStaticFields(StringBuilder builder, TargetClassModel model)
    {
        if (EmissionPlan.For(model).HasCompound)
        {
            CompoundSchema.EmitStaticFields(builder, model);
            return;
        }
        SchemaComponent.EmitStaticFields(builder, model);
    }

    private static void EmitResolveSchemaField(StringBuilder builder, bool usePath = false)
    {
        SchemaComponent.EmitResolveSchemaField(builder, usePath: usePath);
    }

    // ──────────────────────────────────────────────────────────
    //  FORMAT OPTIONS & PRIMITIVES
    // ──────────────────────────────────────────────────────────

    private static void EmitFormatOptionsAndValidation(
        StringBuilder builder,
        TargetClassModel model
    )
    {
        EmitBuildFormatOptions(builder, model);
        builder.AppendLine();
        EmitValidateReader(builder);
    }

    private static void EmitBuildFormatOptions(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Translates the generator's options into the Parquet.Net options the writer accepts."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    private static global::Parquet.ParquetOptions BuildFormatOptions(global::Parquet.SourceGenerator.ParquetSerializerOptions options)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        var formatOptions = new global::Parquet.ParquetOptions");
        builder.AppendLine("        {");
        builder.AppendLine("            CompressionMethod = options.CompressionMethod switch");
        builder.AppendLine("            {");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.None =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.None,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Gzip =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.Gzip,");
        builder.AppendLine("                // Parquet.Net spells this one in caps.");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Lz4 =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.LZ4,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Brotli =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.Brotli,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Zstd =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.Zstd,");
        builder.AppendLine("                _ => global::Parquet.CompressionMethod.Snappy,");
        builder.AppendLine("            },");
        builder.AppendLine("        };");
        builder.AppendLine();
        builder.AppendLine("        if (options.CompressionLevel.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.CompressionLevel = options.CompressionLevel.Value switch"
        );
        builder.AppendLine("            {");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionLevel.Optimal =>"
        );
        builder.AppendLine(
            "                    global::System.IO.Compression.CompressionLevel.Optimal,"
        );
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionLevel.Fastest =>"
        );
        builder.AppendLine(
            "                    global::System.IO.Compression.CompressionLevel.Fastest,"
        );
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionLevel.NoCompression =>"
        );
        builder.AppendLine(
            "                    global::System.IO.Compression.CompressionLevel.NoCompression,"
        );
        builder.AppendLine(
            "                _ => global::System.IO.Compression.CompressionLevel.SmallestSize,"
        );
        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (options.DictionaryEncodingThreshold.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.DictionaryEncodingThreshold = options.DictionaryEncodingThreshold.Value;"
        );
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (options.DictionaryEncodingSampleSize.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.DictionaryEncodingSampleSize = options.DictionaryEncodingSampleSize.Value;"
        );
        builder.AppendLine("        }");

        foreach (var prop in model.Properties)
        {
            if (prop.Encoding != ColumnEncoding.Default)
            {
                string hintValue = prop.Encoding switch
                {
                    ColumnEncoding.Dictionary => "global::Parquet.EncodingHint.Dictionary",
                    ColumnEncoding.DeltaBinaryPacked =>
                        "global::Parquet.EncodingHint.DeltaBinaryPacked",
                    ColumnEncoding.ByteSplitStream =>
                        "global::Parquet.EncodingHint.ByteSplitStream",
                    _ => "global::Parquet.EncodingHint.Default",
                };
                builder.AppendLine(
                    $"        formatOptions.ColumnEncodingHints[\"{prop.ParquetColumnName}\"] = {hintValue};"
                );
            }
        }

        builder.AppendLine();
        builder.AppendLine("        foreach (var kvp in options.ColumnEncodingHints)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.ColumnEncodingHints[kvp.Key] = kvp.Value switch"
        );
        builder.AppendLine("            {");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetColumnEncoding.Dictionary =>"
        );
        builder.AppendLine("                    global::Parquet.EncodingHint.Dictionary,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetColumnEncoding.DeltaBinaryPacked =>"
        );
        builder.AppendLine("                    global::Parquet.EncodingHint.DeltaBinaryPacked,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetColumnEncoding.ByteSplitStream =>"
        );
        builder.AppendLine("                    global::Parquet.EncodingHint.ByteSplitStream,");
        builder.AppendLine("                _ => global::Parquet.EncodingHint.Default,");
        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return formatOptions;");
        builder.AppendLine("    }");
    }

    private static void EmitValidateReader(StringBuilder builder)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Validates the ParquetReader against configured defensive security bounds."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    private static void ValidateReader(");
        builder.AppendLine("        global::Parquet.ParquetReader reader,");
        builder.AppendLine(
            "        global::Parquet.SourceGenerator.ParquetSerializerOptions options)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        int rowGroupCount = reader.RowGroupCount;");
        builder.AppendLine(
            "        if (rowGroupCount < 0 || rowGroupCount > options.MaxRowGroupCount)"
        );
        builder.AppendLine("        {");
        builder.AppendLine(
            "            throw new global::System.IO.InvalidDataException($\"Row group count {rowGroupCount} is invalid or exceeds maximum allowed {options.MaxRowGroupCount}.\");"
        );
        builder.AppendLine("        }");
        builder.AppendLine("        int maxDepth = 0;");
        builder.AppendLine("        foreach (var field in reader.Schema.Fields)");
        builder.AppendLine("        {");
        builder.AppendLine("            int d = GetFieldDepth(field);");
        builder.AppendLine("            if (d > maxDepth) maxDepth = d;");
        builder.AppendLine("        }");
        builder.AppendLine("        if (maxDepth > options.MaxNestingDepth)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            throw new global::System.IO.InvalidDataException($\"Schema nesting depth {maxDepth} exceeds maximum allowed {options.MaxNestingDepth}.\");"
        );
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine(
            "    private static int GetFieldDepth(global::Parquet.Schema.Field field)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        if (field is global::Parquet.Schema.StructField sf)");
        builder.AppendLine("        {");
        builder.AppendLine("            int max = 0;");
        builder.AppendLine("            foreach (var child in sf.Fields)");
        builder.AppendLine("            {");
        builder.AppendLine("                int d = GetFieldDepth(child);");
        builder.AppendLine("                if (d > max) max = d;");
        builder.AppendLine("            }");
        builder.AppendLine("            return 1 + max;");
        builder.AppendLine("        }");
        builder.AppendLine("        if (field is global::Parquet.Schema.ListField lf)");
        builder.AppendLine("        {");
        builder.AppendLine("            return 1 + GetFieldDepth(lf.Item);");
        builder.AppendLine("        }");
        builder.AppendLine("        if (field is global::Parquet.Schema.MapField mf)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            return 1 + global::System.Math.Max(GetFieldDepth(mf.Key), GetFieldDepth(mf.Value));"
        );
        builder.AppendLine("        }");
        builder.AppendLine("        return 1;");
        builder.AppendLine("    }");
    }

    private static string GetWritePrimitiveCall(
        LeafColumn col,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        if (col.IsListLeaf)
        {
            // List lane: values + def + rep arrays sized by written entries (docs/15 §1.2).
            string packedL = col.PackedType;
            return $"{indent}await groupWriter.WriteAllPartsAsync<{packedL}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{packedL}>({bufName}, 0, nonNullCount_{col.Slot}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{col.Slot}, 0, posCount_{col.Slot}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(repLevels_{col.Slot}, 0, posCount_{col.Slot}),\n"
                + $"{indent}    cancellationToken: cancellationToken);";
        }

        if (col.IsCompound)
        {
            // Compound-path leaf: packed values plus a definition ladder; the group's own
            // optionality means even a non-nullable leaf needs levels (docs/15 §1).
            string packed = col.PackedType;
            return $"{indent}await groupWriter.WriteAllPartsAsync<{packed}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{packed}>({bufName}, 0, nonNullCount_{col.Slot}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{col.Slot}, 0, count),\n"
                + $"{indent}    null,\n"
                + $"{indent}    cancellationToken: cancellationToken);";
        }

        PropertyModel prop = col.Leaf;
        int propIndex = col.Slot;
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (BufferPoolComponent.UsesWriteAllParts(prop))
        {
            string nonNullType = BufferPoolComponent.GetNonNullableBufferType(prop);
            return $"{indent}await groupWriter.WriteAllPartsAsync<{nonNullType}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{nonNullType}>({bufName}, 0, nonNullCount_{propIndex}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{propIndex}, 0, count),\n"
                + $"{indent}    null,\n"
                + $"{indent}    cancellationToken: cancellationToken);";
        }
        else if (isString)
        {
            string memType = prop.IsNullable
                ? "global::System.ReadOnlyMemory<char>?"
                : "global::System.ReadOnlyMemory<char>";
            return $"{indent}await groupWriter.WriteAsync<global::System.ReadOnlyMemory<char>>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (isByteArray)
        {
            string memType = prop.IsNullable
                ? "global::System.ReadOnlyMemory<byte>?"
                : "global::System.ReadOnlyMemory<byte>";
            return $"{indent}await groupWriter.WriteAsync<global::System.ReadOnlyMemory<byte>>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Guid)
        {
            return $"{indent}await groupWriter.WriteAsync<global::System.Guid>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<global::System.Guid>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.DateOnly)
        {
            string memType = prop.IsNullable
                ? "global::System.DateTime?"
                : "global::System.DateTime";
            return $"{indent}await groupWriter.WriteAsync<global::System.DateTime>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            return $"{indent}await groupWriter.WriteAsync<{underlying}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{underlying}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeSpan)
        {
            return $"{indent}await groupWriter.WriteAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<int>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeSpan)
        {
            string memType = prop.IsNullable ? "int?" : "int";
            return $"{indent}await groupWriter.WriteAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeOnly)
        {
            string memType = prop.IsNullable ? "long?" : "long";
            return $"{indent}await groupWriter.WriteAsync<long>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else
        {
            string structType = prop.TypeName.TrimEnd('?');
            return $"{indent}await groupWriter.WriteAsync<{structType}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{structType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
    }

    /// <summary>
    /// Emits a column read, gated on the column-chunk NullCount statistic (issue #150).
    /// For nullable columns whose entire chunk is null, the data pages are never opened:
    /// the rented buffer is zeroed instead, skipping I/O, decompression and decoding.
    /// Columns without statistics (or partial nulls) fall through to the standard read.
    /// </summary>
    /// <summary>
    /// True when this column may legitimately be absent from a file the generated reader is asked
    /// to read: an optional flat column, which schema evolution allows a producer to drop.
    /// Required columns cannot be missing (resolution throws) and nested leaves are outside the
    /// documented compatibility envelope.
    /// </summary>
    private static bool SupportsMissingColumn(LeafColumn col) =>
        !col.IsCompound && !col.IsListLeaf && col.Leaf.IsNullable;

    /// <summary>
    /// Emits the one-line schema resolution for a column. Columns that can go missing capture the
    /// absence flag; the rest discard it, because for them resolution either succeeds or throws.
    /// </summary>
    internal static string EmitResolveFieldLine(LeafColumn col, string indent)
    {
        string missingArg = SupportsMissingColumn(col) ? $"out bool missing_{col.Slot}" : "out _";
        return $"{indent}var field_{col.Slot} = ResolveSchemaField(fileFields, {col.Slot}, _field_{col.Slot}, ref fieldsByName, {missingArg});";
    }

    internal static void EmitReadWithNullBypass(
        StringBuilder builder,
        LeafColumn col,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        if (col.IsListLeaf)
        {
            // Entries run ahead of rowCount for multi-element lists: size from the column
            // metadata and re-rent on growth (docs/15 §2.3 — values buffer must cover
            // NumValues, the packed lane follows inside it).
            string packedL = col.PackedType;
            builder.AppendLine(
                $"{indent}var entries_{col.Slot} = checked((int)groupReader.GetMetadata({fieldAccess}).MetaData.NumValues);"
            );
            builder.AppendLine(
                $"{indent}if (entries_{col.Slot} < 0 || entries_{col.Slot} > options.MaxAllocationValues)"
            );
            builder.AppendLine($"{indent}{{");
            builder.AppendLine(
                $"{indent}    throw new global::System.IO.InvalidDataException($\"Column '{col.Leaf.Name}' NumValues ({{entries_{col.Slot}}}) is invalid or exceeds maximum allowed {{options.MaxAllocationValues}}.\");"
            );
            builder.AppendLine($"{indent}}}");
            builder.AppendLine($"{indent}if (entries_{col.Slot} > defLevels_{col.Slot}.Length)");
            builder.AppendLine($"{indent}{{");
            builder.AppendLine(
                $"{indent}    var ndL_{col.Slot} = global::System.Buffers.ArrayPool<int>.Shared.Rent(entries_{col.Slot});"
            );
            builder.AppendLine(
                $"{indent}    global::System.Buffers.ArrayPool<int>.Shared.Return(defLevels_{col.Slot}, clearArray: false);"
            );
            builder.AppendLine($"{indent}    defLevels_{col.Slot} = ndL_{col.Slot};");
            builder.AppendLine(
                $"{indent}    var nrL_{col.Slot} = global::System.Buffers.ArrayPool<int>.Shared.Rent(entries_{col.Slot});"
            );
            builder.AppendLine(
                $"{indent}    global::System.Buffers.ArrayPool<int>.Shared.Return(repLevels_{col.Slot}, clearArray: false);"
            );
            builder.AppendLine($"{indent}    repLevels_{col.Slot} = nrL_{col.Slot};");
            builder.AppendLine(
                $"{indent}    var nvL_{col.Slot} = global::System.Buffers.ArrayPool<{packedL}>.Shared.Rent(entries_{col.Slot});"
            );
            builder.AppendLine(
                $"{indent}    global::System.Buffers.ArrayPool<{packedL}>.Shared.Return(buffer_{col.Slot}, clearArray: true);"
            );
            builder.AppendLine($"{indent}    buffer_{col.Slot} = nvL_{col.Slot};");
            builder.AppendLine($"{indent}}}");
            builder.AppendLine($"{indent}await groupReader.ReadRawAsync<{packedL}>(");
            builder.AppendLine($"{indent}    {fieldAccess},");
            builder.AppendLine(
                $"{indent}    new global::System.Memory<{packedL}>({bufName}, 0, entries_{col.Slot}),"
            );
            builder.AppendLine(
                $"{indent}    new global::System.Memory<int>(defLevels_{col.Slot}, 0, entries_{col.Slot}),"
            );
            builder.AppendLine(
                $"{indent}    new global::System.Memory<int>(repLevels_{col.Slot}, 0, entries_{col.Slot}),"
            );
            builder.AppendLine($"{indent}    cancellationToken);");
            return;
        }

        if (col.IsCompound)
        {
            // Struct-path leaves always carry a definition ladder — read raw with levels.
            // Entries == rowCount for structs (maxRep 0), so rowCount sizes everything.
            string packed = col.PackedType;
            builder.AppendLine($"{indent}await groupReader.ReadRawAsync<{packed}>(");
            builder.AppendLine($"{indent}    {fieldAccess},");
            builder.AppendLine(
                $"{indent}    new global::System.Memory<{packed}>({bufName}, 0, rowCount),"
            );
            builder.AppendLine(
                $"{indent}    new global::System.Memory<int>(defLevels_{col.Slot}, 0, rowCount),"
            );
            builder.AppendLine($"{indent}    null,");
            builder.AppendLine($"{indent}    cancellationToken);");
            return;
        }

        PropertyModel prop = col.Leaf;
        int propIndex = col.Slot;
        if (!prop.IsNullable)
        {
            builder.AppendLine(GetReadPrimitiveCall(prop, fieldAccess, bufName, indent));
            return;
        }

        builder.AppendLine(
            $"{indent}// The column is absent from the file (optional-column schema evolution) or the chunk is"
        );
        builder.AppendLine(
            $"{indent}// entirely null: either way the answer is nulls, with no page read, decompression or decoding."
        );
        builder.AppendLine(
            $"{indent}var chunkStats_{propIndex} = missing_{propIndex} ? null : groupReader.GetStatistics({fieldAccess});"
        );
        builder.AppendLine(
            $"{indent}if (missing_{propIndex} || chunkStats_{propIndex}?.NullCount == rowCount)"
        );
        builder.AppendLine($"{indent}{{");
        builder.AppendLine($"{indent}    global::System.Array.Clear({bufName}, 0, rowCount);");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine($"{indent}else");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine(GetReadPrimitiveCall(prop, fieldAccess, bufName, indent + "    "));
        builder.AppendLine($"{indent}}}");
    }

    private static string GetReadPrimitiveCall(
        PropertyModel prop,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (isString)
        {
            // Deduplicating path reads raw UTF-16 spans so cache hits never instantiate a string.
            // Repeated (list) leaves are excluded: their packed lane is not row-aligned.
            return $"{indent}if (deduplicateStrings && {fieldAccess}.MaxRepetitionLevel == 0)\n"
                + $"{indent}{{\n"
                + $"{indent}    await ReadDeduplicatedStringColumnAsync(\n{indent}        groupReader,\n{indent}        {fieldAccess},\n{indent}        {bufName},\n{indent}        rowCount,\n{indent}        stringDeduplicator,\n{indent}        cancellationToken);\n"
                + $"{indent}}}\n"
                + $"{indent}else\n"
                + $"{indent}{{\n"
                + $"{indent}    await groupReader.ReadAsync(\n{indent}        {fieldAccess},\n{indent}        new global::System.Memory<string?>({bufName}, 0, rowCount),\n{indent}        cancellationToken: cancellationToken);\n"
                + $"{indent}}}";
        }
        else if (isByteArray)
        {
            return $"{indent}await groupReader.ReadAsync(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<byte[]?>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Guid)
        {
            string memType = prop.IsNullable ? "global::System.Guid?" : "global::System.Guid";
            return $"{indent}await groupReader.ReadAsync<global::System.Guid>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.DateOnly)
        {
            string memType = prop.IsNullable
                ? "global::System.DateTime?"
                : "global::System.DateTime";
            return $"{indent}await groupReader.ReadAsync<global::System.DateTime>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            string memType = prop.IsNullable ? $"{underlying}?" : underlying;
            return $"{indent}await groupReader.ReadAsync<{underlying}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeSpan)
        {
            string memType = prop.IsNullable ? "int?" : "int";
            return $"{indent}await groupReader.ReadAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeOnly)
        {
            string memType = prop.IsNullable ? "long?" : "long";
            return $"{indent}await groupReader.ReadAsync<long>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else
        {
            string structType = prop.TypeName.TrimEnd('?');
            string memType = prop.IsNullable ? $"{structType}?" : structType;
            return $"{indent}await groupReader.ReadAsync<{structType}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
    }

