    private static void EmitWriteRowGroupAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Writes a single row group chunk using Parquet.Net low-level primitives for maximum speed and Native AOT compatibility."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    internal static async global::System.Threading.Tasks.Task WriteParquetRowGroupAsync("
        );
        builder.AppendLine("        this global::Parquet.ParquetWriter writer,");
        builder.AppendLine(
            $"        global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> chunk,"
        );
        builder.AppendLine(
            "        global::System.Threading.CancellationToken cancellationToken = default)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(writer);");
        builder.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(chunk);");
        builder.AppendLine();
        builder.AppendLine("        int count = chunk.Count;");
        builder.AppendLine("        if (count == 0) return;");
        builder.AppendLine();

        EmitWriteRentalsFor(builder, model, "count");

        builder.AppendLine();
        builder.AppendLine("        try");
        builder.AppendLine("        {");

        if (PropertyMappingComponent.IsSingleFieldBlittableStruct(model))
        {
            string elemType = PropertyMappingComponent.GetSingleFieldBufferElementType(model);
            PropertyModel prop = model.Properties[0];
            builder.AppendLine(
                $"            if (chunk is global::System.Collections.Generic.List<{model.ClassName}> listItems)"
            );
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine(
                $"                if (global::System.Runtime.CompilerServices.Unsafe.SizeOf<{model.ClassName}>() == global::System.Runtime.CompilerServices.Unsafe.SizeOf<{elemType}>())"
            );
            builder.AppendLine("                {");
            builder.AppendLine(
                "                    var span = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(listItems);"
            );
            builder.AppendLine(
                $"                    global::System.Runtime.InteropServices.MemoryMarshal.Cast<{model.ClassName}, {elemType}>(span.Slice(0, count))"
            );
            builder.AppendLine("                        .CopyTo(buffer_0.AsSpan(0, count));");
            builder.AppendLine("                }");
            builder.AppendLine("                else");
            builder.AppendLine("                {");
            builder.AppendLine("                    for (int i = 0; i < count; i++)");
            builder.AppendLine("                    {");
            builder.AppendLine($"                        buffer_0[i] = listItems[i].{prop.Name};");
            builder.AppendLine("                    }");
            builder.AppendLine("                }");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine("                    var item = listItems[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");
            builder.AppendLine($"            else if (chunk is {model.ClassName}[] arrayItems)");
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine(
                $"                if (global::System.Runtime.CompilerServices.Unsafe.SizeOf<{model.ClassName}>() == global::System.Runtime.CompilerServices.Unsafe.SizeOf<{elemType}>())"
            );
            builder.AppendLine("                {");
            builder.AppendLine(
                $"                    global::System.Runtime.InteropServices.MemoryMarshal.Cast<{model.ClassName}, {elemType}>(arrayItems.AsSpan(0, count))"
            );
            builder.AppendLine("                        .CopyTo(buffer_0.AsSpan(0, count));");
            builder.AppendLine("                }");
            builder.AppendLine("                else");
            builder.AppendLine("                {");
            builder.AppendLine("                    for (int i = 0; i < count; i++)");
            builder.AppendLine("                    {");
            builder.AppendLine($"                        buffer_0[i] = arrayItems[i].{prop.Name};");
            builder.AppendLine("                    }");
            builder.AppendLine("                }");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine($"                    buffer_0[i] = arrayItems[i].{prop.Name};");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");
            builder.AppendLine("            else");
            builder.AppendLine("            {");
            builder.AppendLine("                int idx = 0;");
            builder.AppendLine("                foreach (var item in chunk)");
            builder.AppendLine("                {");
            EmitPropertyAssignmentsIndexed(
                builder,
                model,
                "buffer_",
                prefix: "                    "
            );
            builder.AppendLine("                    idx++;");
            builder.AppendLine("                }");
            builder.AppendLine("            }");
        }
        else
        {
            // List fast path
            builder.AppendLine(
                $"            if (chunk is global::System.Collections.Generic.List<{model.ClassName}> listItems)"
            );
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine("                void ExtractSpan()");
            builder.AppendLine("                {");
            builder.AppendLine(
                "                    var span = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(listItems);"
            );
            EmitUnboundExtractionLoop(builder, model, "span");
            builder.AppendLine("                }");
            builder.AppendLine("                ExtractSpan();");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine("                    var item = listItems[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");

            // Array fast path
            builder.AppendLine($"            else if (chunk is {model.ClassName}[] arrayItems)");
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine("                void ExtractArray()");
            builder.AppendLine("                {");
            EmitUnboundExtractionLoop(builder, model, "arrayItems", sourceIsArray: true);
            builder.AppendLine("                }");
            builder.AppendLine("                ExtractArray();");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine("                    var item = arrayItems[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");

            // Enumerable fallback
            builder.AppendLine("            else");
            builder.AppendLine("            {");
            builder.AppendLine("                int idx = 0;");
            builder.AppendLine("                foreach (var item in chunk)");
            builder.AppendLine("                {");
            EmitPropertyAssignmentsIndexed(
                builder,
                model,
                "buffer_",
                prefix: "                    "
            );
            builder.AppendLine("                    idx++;");
            builder.AppendLine("                }");
            builder.AppendLine("            }");
        }
        builder.AppendLine();

        // Write row group using static pre-allocated DataFields
        builder.AppendLine("            using (var groupWriter = writer.CreateRowGroup())");
        builder.AppendLine("            {");

        LeafColumn[] writeColumns = EmissionPlan.For(model).Columns;
        foreach (LeafColumn col in writeColumns)
        {
            string fieldAccess = $"_field_{col.Slot}";
            builder.AppendLine(GetWritePrimitiveCall(col, fieldAccess, $"buffer_{col.Slot}"));
            if (col.IsCompound || col.IsListLeaf)
            {
                CompoundBuffers.EmitSingleWriteReturn(
                    builder,
                    col,
                    varPrefix: "buffer_",
                    indent: "                "
                );
            }
            else
            {
                BufferPoolComponent.EmitSingleWriteReturn(
                    builder,
                    col.Leaf,
                    col.Slot,
                    indent: "                "
                );
            }
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        finally");
        builder.AppendLine("        {");

        EmitWriteReturnsFor(builder, model);

        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

