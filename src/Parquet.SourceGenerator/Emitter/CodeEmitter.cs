using System;
using System.Text;
using Parquet.SourceGenerator.Emitter.Columnar;
using Parquet.SourceGenerator.Emitter.Components;
using Parquet.SourceGenerator.Emitter.Compound;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Emitter;

/// <summary>
/// Emits high-performance C# extension classes targeting Parquet.Net v6 low-level primitives.
/// Features configurable ParquetSerializerOptions, IAsyncEnumerable streaming, compact 8-byte Int64 microsecond timestamp encoding,
/// parallel multi-row-group reading, zero-allocation Guid binary encoding, static pre-allocated DataFields,
/// O(1) index-check schema field resolution, ArrayPool buffer recycling, zero-copy ReadOnlyMemory overloads,
/// and Native AOT compatibility.
/// </summary>
internal static class CodeEmitter
{
    /// <summary>
    /// Generates complete C# source code string for a given target model.
    /// </summary>
    public static string EmitSource(TargetClassModel model)
    {
        return EmitSource(model, GeneratorConfiguration.Default);
    }

    internal static string EmitSource(TargetClassModel model, GeneratorConfiguration configuration)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine($"// ParquetGeneratorFeatureLevel: {configuration.FeatureLevel}");
        builder.AppendLine($"// ParquetGeneratorVersion: {configuration.GeneratorVersion}");
        builder.AppendLine("#nullable enable");
        builder.AppendLine(
            "#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8629"
        );
        builder.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        // For a nested target ("Outer.Inner") the dotted ClassName resolves in type positions but
        // cannot seed an identifier; the flattened form keeps sibling-nested types apart.
        string extensionsClassName =
            $"{model.ClassName.Replace(".", string.Empty)}ParquetExtensions";

        builder.AppendLine($"public static partial class {extensionsClassName}");
        builder.AppendLine("{");

        EmitSchema(builder, model);
        builder.AppendLine();

        EmitStaticFields(builder, model);
        builder.AppendLine();

        if (model.Properties.Length > 0)
        {
            EmitSchemaHelpers(builder, usePath: EmissionPlan.For(model).HasCompound);
            builder.AppendLine();
        }

        EmitFormatOptionsAndValidation(builder, model);
        builder.AppendLine();

        if (StringDeduplicatorComponent.HasStringProperties(model))
        {
            StringDeduplicatorComponent.EmitStringDeduplicator(builder);
            builder.AppendLine();
        }

        // Shared per-column guards and pooled-buffer returns (#552): one helper each, one call
        // per column, so emitted method complexity does not grow with the column count.
        ColumnHelpersComponent.EmitHelpers(builder, model);
        builder.AppendLine();

        // Streaming row group writer — low level primitives, 100M+ scale, Native AOT compatible
        EmitWriteRowGroupAsync(builder, model);
        builder.AppendLine();

        // Direct columnar hand-off (#137) — caller already owns contiguous column buffers, so the
        // row transpose and its pooled rentals are skipped entirely. All-leaf models only.
        bool emitColumnar = ColumnarBatchComponent.IsSupported(model);
        if (emitColumnar)
        {
            ColumnarBatchComponent.EmitWriters(builder, model);
            builder.AppendLine();
        }

        // Primary write API — async (v6 requires async for writer creation)
        EmitWriteAsync(builder, model);
        builder.AppendLine();

        // Batched streaming write — splits IEnumerable into fixed-size row groups
        EmitWriteBatchedAsync(builder, model);
        builder.AppendLine();

        // IAsyncEnumerable streaming write
        EmitWriteAsyncEnumerable(builder, model);
        builder.AppendLine();

        // Direct array Read API — zero-copy array materialization
        EmitReadArrayAsync(builder, model);
        builder.AppendLine();

        // Streaming Read API — IAsyncEnumerable streaming
        EmitReadStreamAsync(builder, model);
        builder.AppendLine();

        // Zero-copy ReadOnlyMemory overloads
        EmitReadMemoryOverloads(builder, model);

        // Columnar batch read (#147, #508) — flat models only. The batch type is the one the columnar
        // writer above takes, emitted once at namespace scope below.
        if (emitColumnar)
        {
            builder.AppendLine();
            BatchReadComponent.EmitReadBatchesAsync(
                builder,
                model,
                static (b, col, field, buf) => EmitReadWithNullBypass(b, col, field, buf)
            );
        }

        // Row-group predicate pushdown (#149) — the zone-map guard the read loops call.
        if (RowGroupPruningComponent.IsEnabled(model))
        {
            builder.AppendLine();
            RowGroupPruningComponent.EmitAcceptRowGroup(builder, model);
        }

        // Sorted row-group pruning: binary search over footer [Min, Max] statistics (issue #151)
        var sortableColumns = SortedRowGroupPruningComponent.SortableColumns(model);
        if (sortableColumns.Count > 0)
        {
            builder.AppendLine();
            SortedRowGroupPruningComponent.EmitPruningHelpers(builder);
            builder.AppendLine();
            EmitReadPrunedRangeAsync(builder, model);
            SortedRowGroupPruningComponent.EmitLookupOverloads(builder, model, sortableColumns);
        }

        builder.AppendLine("}");

        RowGroupPruningComponent.EmitMetadataStruct(builder, model);
        if (emitColumnar)
        {
            builder.AppendLine();
            ColumnarBatchComponent.EmitBatchStruct(builder, model);
        }

        // Read entry point and its single reader struct (#217, #478). Each axis of the read grid becomes a
        // member rather than a name segment; see docs/19-PUBLIC-API-SURFACE.md. The builder is the
        // only public read surface (#480, docs/48): the internal Read*CoreAsync methods above are
        // the implementations its terminals delegate to, and are not part of the consumer contract.
        ReadBuilderComponent.Emit(builder, model);

        return builder.ToString();
    }

    // ──────────────────────────────────────────────────────────
    //  SCHEMA & STATIC FIELD CACHING
    // ──────────────────────────────────────────────────────────

    private static void EmitSchema(StringBuilder builder, TargetClassModel model)
    {
        if (EmissionPlan.For(model).HasCompound)
        {
            CompoundSchema.EmitSchema(builder, model);
            return;
        }
        SchemaComponent.EmitSchema(builder, model);
    }

    private static void EmitStaticFields(StringBuilder builder, TargetClassModel model)
    {
        if (EmissionPlan.For(model).HasCompound)
        {
            CompoundSchema.EmitStaticFields(builder, model);
            return;
        }
        SchemaComponent.EmitStaticFields(builder, model);
    }

    private static void EmitResolveSchemaField(StringBuilder builder, bool usePath = false)
    {
        SchemaComponent.EmitResolveSchemaField(builder, usePath: usePath, invariantPath: true);
    }

    private static void EmitSchemaHelpers(StringBuilder builder, bool usePath)
    {
        EmitResolveSchemaField(builder, usePath);
        builder.AppendLine();
        SchemaComponent.EmitValidatePhysicalType(builder, invariantPath: true);
        builder.AppendLine();
        SchemaComponent.EmitValidateColumnChunkBounds(builder);
        DictionaryPageComponent.EmitHelpers(builder);
    }

    // ──────────────────────────────────────────────────────────
    //  FORMAT OPTIONS & PRIMITIVES
    // ──────────────────────────────────────────────────────────

    private static void EmitFormatOptionsAndValidation(
        StringBuilder builder,
        TargetClassModel model
    )
    {
        EmitBuildFormatOptions(builder, model);
        builder.AppendLine();
        EmitValidateReader(builder, model);
    }

    /// <summary>
    /// Emits <c>BuildFormatOptions</c> as a one-line forwarder to a nested mapper class.
    /// </summary>
    /// <remarks>
    /// The option-to-Parquet.Net enum mappings name six types that nothing else in the
    /// extensions class uses. Keeping them in a nested class keeps them out of the outer
    /// class's coupling count (CA1506), which every emitted feature competes for.
    /// </remarks>
    private static void EmitBuildFormatOptions(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Translates the generator's options into the Parquet.Net options the writer accepts."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    private static global::Parquet.ParquetOptions BuildFormatOptions(global::Parquet.SourceGenerator.ParquetSerializerOptions options) =>"
        );
        builder.AppendLine("        FormatOptionsMapper.Build(options);");
        builder.AppendLine();
        builder.AppendLine("    private static class FormatOptionsMapper");
        builder.AppendLine("    {");

        var method = new StringBuilder();
        EmitFormatOptionsMapperMethod(method, model);
        foreach (string line in method.ToString().TrimEnd().Split('\n'))
        {
            string trimmed = line.TrimEnd('\r');
            builder.AppendLine(trimmed.Length == 0 ? trimmed : "    " + trimmed);
        }

        builder.AppendLine("    }");
        builder.AppendLine();
        DecompressionGuardComponent.Emit(builder);
    }

