using System.Text;
using Parquet.SourceGenerator.Emitter.Components;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Emitter;

/// <summary>
/// Emits the conditionally-generated Apache Arrow ingestion bridge (<c>{Type}.Arrow.g.cs</c>).
/// </summary>
/// <remarks>
/// This file only exists in compilations that reference Apache.Arrow — the generator gates it on a
/// <c>CompilationProvider</c> flag — so the emitted overloads name Arrow types directly. There is
/// no reflection, no runtime feature test, and no companion package: everything below is ordinary
/// generated text calling Apache.Arrow's public API, exactly like the rest of the emitter calls
/// Parquet.Net's.
/// </remarks>
internal static class ArrowBridgeEmitter
{
    /// <summary>
    /// Whether a bridge can be emitted for this model. Compound members (#176) and leaves with no
    /// Arrow representation opt the whole type out rather than emitting a partial mapping.
    /// </summary>
    public static bool CanEmit(TargetClassModel model) => ArrowMappingComponent.IsSupported(model);

    /// <summary>
    /// Emits the complete <c>{Type}.Arrow.g.cs</c> source for one model.
    /// </summary>
    public static string EmitSource(TargetClassModel model)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine(
            "#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8629"
        );
        builder.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        string extensionsClassName =
            $"{model.ClassName.Replace(".", string.Empty)}ParquetExtensions";

        builder.AppendLine($"public static partial class {extensionsClassName}");
        builder.AppendLine("{");

        bool needsEpoch = false;
        bool needsGuid = false;
        bool needsFixedWidthView = false;
        for (int i = 0; i < model.Properties.Length; i++)
        {
            ArrowLeafMapping map = ArrowMappingComponent.TryMap(model.Properties[i])!;
            needsEpoch |= map.ConvertExpression?.Contains("_arrowUnixEpoch") == true;
            needsGuid |= map.ConvertExpression?.Contains("ArrowGuidFromBigEndian") == true;
            needsFixedWidthView |=
                map.Mode == ArrowExtractionMode.Direct && !model.Properties[i].IsNullable;
        }

        if (needsEpoch)
        {
            builder.AppendLine(
                "    // Unspecified kind on purpose: it is the kind DateOnly.ToDateTime produces on the"
            );
            builder.AppendLine(
                "    // POCO write path, so both paths hand Parquet.Net identical DateTime values."
            );
            builder.AppendLine(
                "    private static readonly global::System.DateTime _arrowUnixEpoch ="
            );
            builder.AppendLine(
                "        new global::System.DateTime(1970, 1, 1, 0, 0, 0, global::System.DateTimeKind.Unspecified);"
            );
            builder.AppendLine();
        }

        EmitValidation(builder, model);
        builder.AppendLine();
        EmitWriteRowGroup(builder, model);

        if (needsFixedWidthView)
        {
            builder.AppendLine();
            EmitFixedWidthView(builder);
        }

        if (needsGuid)
        {
            builder.AppendLine();
            EmitGuidHelper(builder);
        }

        builder.AppendLine("}");

        return builder.ToString();
    }

