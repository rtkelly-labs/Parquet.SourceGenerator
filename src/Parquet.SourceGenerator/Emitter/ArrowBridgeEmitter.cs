    private static void EmitFixedWidthView(StringBuilder builder)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Reinterprets an Arrow fixed-width value buffer as <c>ReadOnlyMemory&lt;T&gt;</c> without"
        );
        builder.AppendLine(
            "    /// copying it. On targets without <c>MemoryMarshal.CreateSpan</c> the values are copied out."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    private static global::System.ReadOnlyMemory<T> ArrowFixedWidthMemory<T>("
        );
        builder.AppendLine("        global::Apache.Arrow.ArrowBuffer buffer,");
        builder.AppendLine("        int offset,");
        builder.AppendLine("        int length)");
        builder.AppendLine("        where T : struct");
        builder.AppendLine("    {");
        builder.AppendLine("#if NET6_0_OR_GREATER");
        builder.AppendLine(
            "        return new ArrowValueMemoryManager<T>(buffer.Memory).Memory.Slice(offset, length);"
        );
        builder.AppendLine("#else");
        builder.AppendLine(
            "        var source = global::System.Runtime.InteropServices.MemoryMarshal.Cast<byte, T>(buffer.Span);"
        );
        builder.AppendLine("        var copy = new T[length];");
        builder.AppendLine("        source.Slice(offset, length).CopyTo(copy);");
        builder.AppendLine("        return copy;");
        builder.AppendLine("#endif");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("#if NET6_0_OR_GREATER");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Views an Arrow byte buffer as a typed <c>Memory&lt;T&gt;</c>. The buffer is owned by the"
        );
        builder.AppendLine(
            "    /// RecordBatch and outlives the write, so the manager holds no lifetime of its own."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    private sealed class ArrowValueMemoryManager<T> : global::System.Buffers.MemoryManager<T>"
        );
        builder.AppendLine("        where T : struct");
        builder.AppendLine("    {");
        builder.AppendLine("        private readonly global::System.ReadOnlyMemory<byte> _bytes;");
        builder.AppendLine();
        builder.AppendLine(
            "        public ArrowValueMemoryManager(global::System.ReadOnlyMemory<byte> bytes)"
        );
        builder.AppendLine("        {");
        builder.AppendLine("            _bytes = bytes;");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        public override global::System.Span<T> GetSpan()");
        builder.AppendLine("        {");
        builder.AppendLine("            global::System.ReadOnlySpan<byte> span = _bytes.Span;");
        builder.AppendLine(
            "            return global::System.Runtime.InteropServices.MemoryMarshal.Cast<byte, T>("
        );
        builder.AppendLine(
            "                global::System.Runtime.InteropServices.MemoryMarshal.CreateSpan("
        );
        builder.AppendLine(
            "                    ref global::System.Runtime.InteropServices.MemoryMarshal.GetReference(span),"
        );
        builder.AppendLine("                    span.Length));");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine(
            "        public override global::System.Buffers.MemoryHandle Pin(int elementIndex = 0)"
        );
        builder.AppendLine("        {");
        builder.AppendLine(
            "            return _bytes.Slice(elementIndex * global::System.Runtime.CompilerServices.Unsafe.SizeOf<T>()).Pin();"
        );
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        public override void Unpin()");
        builder.AppendLine("        {");
        builder.AppendLine("            // The Arrow buffer owns the memory; nothing to release.");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        protected override void Dispose(bool disposing)");
        builder.AppendLine("        {");
        builder.AppendLine("            // No unmanaged state of our own.");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("#endif");
    }

    private static void EmitGuidHelper(StringBuilder builder)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Reads a 16-byte Arrow fixed-size binary value as an RFC 4122 (big-endian) UUID."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    private static global::System.Guid ArrowGuidFromBigEndian(");
        builder.AppendLine("        global::System.ReadOnlySpan<byte> bytes)");
        builder.AppendLine("    {");
        builder.AppendLine(
            "        int a = (bytes[0] << 24) | (bytes[1] << 16) | (bytes[2] << 8) | bytes[3];"
        );
        builder.AppendLine("        short b = (short)((bytes[4] << 8) | bytes[5]);");
        builder.AppendLine("        short c = (short)((bytes[6] << 8) | bytes[7]);");
        builder.AppendLine("        return new global::System.Guid(");
        builder.AppendLine("            a, b, c,");
        builder.AppendLine("            bytes[8], bytes[9], bytes[10], bytes[11],");
        builder.AppendLine("            bytes[12], bytes[13], bytes[14], bytes[15]);");
        builder.AppendLine("    }");
    }

    private static string Substitute(
        string template,
        string arrayVar,
        string valuesVar,
        string indexVar
    )
    {
        return template
            .Replace("{ARR}", arrayVar)
            .Replace("{VALS}", valuesVar)
            .Replace("{I}", indexVar);
    }
