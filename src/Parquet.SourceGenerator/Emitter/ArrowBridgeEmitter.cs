    private static void EmitWriteRowGroup(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            $"    /// Writes one Apache Arrow <c>RecordBatch</c> as a single Parquet row group using the"
        );
        builder.AppendLine(
            $"    /// <c>{model.ClassName}</c> schema. Columns are matched by name and validated strictly;"
        );
        builder.AppendLine(
            "    /// fixed-width Arrow buffers are handed to the writer without a copy or an ArrayPool rental."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    /// <remarks>Call it qualified — it is a plain static method, not an extension.</remarks>"
        );
        builder.AppendLine(
            $"    /// <remarks>Requires Apache.Arrow {ArrowMappingComponent.SupportedArrowFloor} or later.</remarks>"
        );
        builder.AppendLine(
            "    public static async global::System.Threading.Tasks.Task WriteParquetRowGroupAsync("
        );
        // Deliberately NOT an extension method. RecordBatch carries no generic parameter, so an
        // extension overload would collide across every [ParquetSerializable] type in scope — the
        // POCO overload is disambiguated by IReadOnlyCollection<T>, this one could not be. Callers
        // qualify it: FooParquetExtensions.WriteParquetRowGroupAsync(writer, batch).
        builder.AppendLine("        global::Parquet.ParquetWriter writer,");
        builder.AppendLine("        global::Apache.Arrow.RecordBatch batch,");
        builder.AppendLine(
            "        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,"
        );
        builder.AppendLine(
            "        global::System.Threading.CancellationToken cancellationToken = default)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(writer);");
        builder.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(batch);");
        builder.AppendLine();
        builder.AppendLine(
            "        // Row-group granularity is the unit of this overload; compression and the other"
        );
        builder.AppendLine(
            "        // serializer options belong to the ParquetWriter the caller already created."
        );
        builder.AppendLine("        _ = options;");
        builder.AppendLine();
        builder.AppendLine("        ValidateArrowRecordBatch(batch);");
        builder.AppendLine();
        builder.AppendLine("        int count = batch.Length;");
        builder.AppendLine("        if (count == 0) return;");
        builder.AppendLine();
        for (int i = 0; i < model.Properties.Length; i++)
        {
            EmitColumnDeclarations(builder, model.Properties[i], i);
        }
        builder.AppendLine();
        builder.AppendLine("        using (var groupWriter = writer.CreateRowGroup())");
        builder.AppendLine("        {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            builder.AppendLine("            try");
            builder.AppendLine("            {");
            EmitColumn(builder, model.Properties[i], i);
            EmitColumnWrite(builder, model.Properties[i], i);
            builder.AppendLine("            }");
            builder.AppendLine("            finally");
            builder.AppendLine("            {");
            EmitColumnCleanup(builder, model.Properties[i], i);
            builder.AppendLine("            }");
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitColumnWrite(StringBuilder builder, PropertyModel prop, int slot)
    {
        string fieldAccess = $"_field_{slot}";
        if (BufferPoolComponent.UsesWriteAllParts(prop))
        {
            string nonNullableElementType = BufferPoolComponent.GetNonNullableBufferType(prop);
            builder.AppendLine(
                $"                await groupWriter.WriteAllPartsAsync<{nonNullableElementType}>("
            );
            builder.AppendLine($"                    {fieldAccess},");
            builder.AppendLine($"                    lane_{slot},");
            builder.AppendLine($"                    levels_{slot}.Slice(0, count),");
            builder.AppendLine("                    null,");
            builder.AppendLine(
                "                    cancellationToken: cancellationToken).ConfigureAwait(false);"
            );
            return;
        }

        string columnElementType = BufferPoolComponent.GetWriteBufferElementType(prop).TrimEnd('?');
        builder.AppendLine($"                await groupWriter.WriteAsync<{columnElementType}>(");
        builder.AppendLine($"                    {fieldAccess},");
        builder.AppendLine($"                    lane_{slot}.Slice(0, count),");
        builder.AppendLine(
            "                    cancellationToken: cancellationToken).ConfigureAwait(false);"
        );
    }

    private static void EmitColumn(StringBuilder builder, PropertyModel prop, int slot)
    {
        ArrowLeafMapping map = ArrowMappingComponent.TryMap(prop)!;
        string name = EmittedText.Literal(prop.ParquetColumnName);
        string arr = $"arrow_{slot}";
        builder.AppendLine();
        builder.AppendLine(
            $"            // column {slot}: {EmittedText.Comment(prop.ParquetColumnName)}"
        );
        builder.AppendLine($"                var {arr} = ({map.ArrowArrayType})batch.Column(");
        builder.AppendLine(
            $"                    batch.Schema.GetFieldIndex({name}, global::System.StringComparer.Ordinal));"
        );

        switch (map.Mode)
        {
            case ArrowExtractionMode.Direct when !prop.IsNullable:
                EmitDirectRequired(builder, map, arr, slot);
                break;
            case ArrowExtractionMode.Utf8:
                EmitUtf8(builder, prop, arr, slot);
                break;
            case ArrowExtractionMode.Binary:
                EmitBinary(builder, prop, arr, slot);
                break;
            case ArrowExtractionMode.Convert when !prop.IsNullable:
                EmitConvertRequired(builder, map, arr, slot);
                break;
            default:
                EmitPackedNullable(builder, map, arr, slot);
                break;
        }
    }

    private static void EmitColumnDeclarations(StringBuilder builder, PropertyModel prop, int slot)
    {
        ArrowLeafMapping map = ArrowMappingComponent.TryMap(prop)!;

        switch (map.Mode)
        {
            case ArrowExtractionMode.Direct when !prop.IsNullable:
                return;

            case ArrowExtractionMode.Utf8:
            {
                string element = prop.IsNullable
                    ? "global::System.ReadOnlyMemory<char>?"
                    : "global::System.ReadOnlyMemory<char>";
                builder.AppendLine($"        {element}[]? buffer_{slot} = null;");
                builder.AppendLine($"        char[]? chars_{slot} = null;");
                return;
            }

            case ArrowExtractionMode.Binary:
            {
                string element = prop.IsNullable
                    ? "global::System.ReadOnlyMemory<byte>?"
                    : "global::System.ReadOnlyMemory<byte>";
                builder.AppendLine($"        {element}[]? buffer_{slot} = null;");
                return;
            }

            case ArrowExtractionMode.Convert when !prop.IsNullable:
                builder.AppendLine($"        {map.ParquetElementType}[]? buffer_{slot} = null;");
                return;

            default:
                builder.AppendLine($"        {map.ParquetElementType}[]? packed_{slot} = null;");
                builder.AppendLine($"        int[]? defLevels_{slot} = null;");
                builder.AppendLine($"        int nonNullCount_{slot} = 0;");
                return;
        }
    }

    private static void EmitDirectRequired(
        StringBuilder builder,
        ArrowLeafMapping map,
        string arr,
        int slot
    )
    {
        string t = map.ParquetElementType;
        builder.AppendLine(
            "                // Zero-copy: the Arrow value buffer is reinterpreted in place."
        );
        builder.AppendLine(
            $"                var lane_{slot} = ArrowFixedWidthMemory<{t}>({arr}.ValueBuffer, {arr}.Offset, count);"
        );
    }

    private static void EmitConvertRequired(
        StringBuilder builder,
        ArrowLeafMapping map,
        string arr,
        int slot
    )
    {
        string t = map.ParquetElementType;
        string convert = Substitute(map.ConvertExpression!, arr, "values", "row");

        builder.AppendLine(
            $"                buffer_{slot} = global::System.Buffers.ArrayPool<{t}>.Shared.Rent(count);"
        );
        builder.AppendLine($"                    void Fill_{slot}()");
        builder.AppendLine("                    {");
        if (map.UsesValuesSpan)
        {
            builder.AppendLine($"                        var values = {arr}.Values;");
        }
        builder.AppendLine("                        for (int row = 0; row < count; row++)");
        builder.AppendLine("                        {");
        builder.AppendLine($"                            buffer_{slot}[row] = {convert};");
        builder.AppendLine("                        }");
        builder.AppendLine("                    }");
        builder.AppendLine($"                    Fill_{slot}();");
        builder.AppendLine(
            $"                    var lane_{slot} = new global::System.ReadOnlyMemory<{t}>(buffer_{slot}, 0, count);"
        );
    }

    private static void EmitPackedNullable(
        StringBuilder builder,
        ArrowLeafMapping map,
        string arr,
        int slot
    )
    {
        string t = map.ParquetElementType;
        bool direct = map.Mode == ArrowExtractionMode.Direct;
        string valueExpr = direct
            ? "values[row]"
            : Substitute(map.ConvertExpression!, arr, "values", "row");
        bool needsValues = direct || map.UsesValuesSpan;

        builder.AppendLine(
            "                // The Arrow validity bitmap is the definition-level source: packed values"
        );
        builder.AppendLine(
            "                // for the writer, one def level per row. No caller-supplied levels needed."
        );
        builder.AppendLine(
            $"                packed_{slot} = global::System.Buffers.ArrayPool<{t}>.Shared.Rent(count);"
        );
        builder.AppendLine(
            $"                defLevels_{slot} = global::System.Buffers.ArrayPool<int>.Shared.Rent(count);"
        );
        builder.AppendLine($"                    void Pack_{slot}()");
        builder.AppendLine("                    {");
        if (needsValues)
        {
            builder.AppendLine($"                        var values = {arr}.Values;");
        }
        builder.AppendLine($"                        if ({arr}.NullCount == 0)");
        builder.AppendLine("                        {");
        builder.AppendLine("                            for (int row = 0; row < count; row++)");
        builder.AppendLine("                            {");
        builder.AppendLine($"                                packed_{slot}[row] = {valueExpr};");
        builder.AppendLine($"                                defLevels_{slot}[row] = 1;");
        builder.AppendLine("                            }");
        builder.AppendLine($"                            nonNullCount_{slot} = count;");
        builder.AppendLine("                            return;");
        builder.AppendLine("                        }");
        builder.AppendLine();
        builder.AppendLine("                        for (int row = 0; row < count; row++)");
        builder.AppendLine("                        {");
        builder.AppendLine($"                            if ({arr}.IsValid(row))");
        builder.AppendLine("                            {");
        builder.AppendLine(
            $"                                packed_{slot}[nonNullCount_{slot}++] = {valueExpr};"
        );
        builder.AppendLine($"                                defLevels_{slot}[row] = 1;");
        builder.AppendLine("                            }");
        builder.AppendLine("                            else");
        builder.AppendLine("                            {");
        builder.AppendLine($"                                defLevels_{slot}[row] = 0;");
        builder.AppendLine("                            }");
        builder.AppendLine("                        }");
        builder.AppendLine("                    }");
        builder.AppendLine($"                    Pack_{slot}();");
        builder.AppendLine(
            $"                    var lane_{slot} = new global::System.ReadOnlyMemory<{t}>(packed_{slot}, 0, nonNullCount_{slot});"
        );
        builder.AppendLine(
            $"                    var levels_{slot} = new global::System.ReadOnlyMemory<int>(defLevels_{slot}, 0, count);"
        );
    }

    private static void EmitUtf8(StringBuilder builder, PropertyModel prop, string arr, int slot)
    {
        string element = prop.IsNullable
            ? "global::System.ReadOnlyMemory<char>?"
            : "global::System.ReadOnlyMemory<char>";
        string nullLiteral = prop.IsNullable ? "null" : $"default({element})";

        builder.AppendLine(
            "                // Utf8 offsets are materialized once into a single rented char[]; each row"
                + " gets a slice of it,"
        );
        builder.AppendLine(
            "                // so N strings cost one rental rather than N string allocations."
        );
        builder.AppendLine(
            $"                buffer_{slot} = global::System.Buffers.ArrayPool<{element}>.Shared.Rent(count);"
        );
        builder.AppendLine($"                    void Fill_{slot}()");
        builder.AppendLine("                    {");
        builder.AppendLine("                        int totalChars = 0;");
        builder.AppendLine("                        for (int row = 0; row < count; row++)");
        builder.AppendLine("                        {");
        builder.AppendLine($"                            totalChars += {arr}.GetValueLength(row);");
        builder.AppendLine("                        }");
        builder.AppendLine(
            $"                        chars_{slot} = global::System.Buffers.ArrayPool<char>.Shared.Rent(totalChars > 0 ? totalChars : 1);"
        );
        builder.AppendLine("                        int pos = 0;");
        builder.AppendLine("                        for (int row = 0; row < count; row++)");
        builder.AppendLine("                        {");
        builder.AppendLine($"                            if (!{arr}.IsValid(row))");
        builder.AppendLine("                            {");
        builder.AppendLine($"                                buffer_{slot}[row] = {nullLiteral};");
        builder.AppendLine("                                continue;");
        builder.AppendLine("                            }");
        builder.AppendLine("#if NET6_0_OR_GREATER");
        builder.AppendLine(
            $"                            int written = global::System.Text.Encoding.UTF8.GetChars({arr}.GetBytes(row), chars_{slot}.AsSpan(pos));"
        );
        builder.AppendLine("#else");
        builder.AppendLine($"                            string text = {arr}.GetString(row);");
        builder.AppendLine(
            $"                            text.CopyTo(0, chars_{slot}, pos, text.Length);"
        );
        builder.AppendLine("                            int written = text.Length;");
        builder.AppendLine("#endif");
        builder.AppendLine(
            $"                            buffer_{slot}[row] = new global::System.ReadOnlyMemory<char>(chars_{slot}, pos, written);"
        );
        builder.AppendLine("                            pos += written;");
        builder.AppendLine("                        }");
        builder.AppendLine("                    }");
        builder.AppendLine($"                    Fill_{slot}();");
        builder.AppendLine(
            $"                    var lane_{slot} = new global::System.ReadOnlyMemory<{element}>(buffer_{slot}, 0, count);"
        );
    }

    private static void EmitBinary(StringBuilder builder, PropertyModel prop, string arr, int slot)
    {
        string element = prop.IsNullable
            ? "global::System.ReadOnlyMemory<byte>?"
            : "global::System.ReadOnlyMemory<byte>";
        string nullLiteral = prop.IsNullable ? "null" : $"default({element})";

        builder.AppendLine(
            "                // Each row is a slice of the Arrow value buffer — the payload is never copied."
        );
        builder.AppendLine(
            $"                buffer_{slot} = global::System.Buffers.ArrayPool<{element}>.Shared.Rent(count);"
        );
        builder.AppendLine($"                    void Fill_{slot}()");
        builder.AppendLine("                    {");
        builder.AppendLine(
            $"                        global::System.ReadOnlyMemory<byte> payload = {arr}.ValueBuffer.Memory;"
        );
        builder.AppendLine(
            $"                        global::System.ReadOnlySpan<int> offsets = {arr}.ValueOffsets;"
        );
        builder.AppendLine("                        for (int row = 0; row < count; row++)");
        builder.AppendLine("                        {");
        builder.AppendLine($"                            if (!{arr}.IsValid(row))");
        builder.AppendLine("                            {");
        builder.AppendLine($"                                buffer_{slot}[row] = {nullLiteral};");
        builder.AppendLine("                                continue;");
        builder.AppendLine("                            }");
        builder.AppendLine(
            $"                            buffer_{slot}[row] = payload.Slice(offsets[row], offsets[row + 1] - offsets[row]);"
        );
        builder.AppendLine("                        }");
        builder.AppendLine("                    }");
        builder.AppendLine($"                    Fill_{slot}();");
        builder.AppendLine(
            $"                    var lane_{slot} = new global::System.ReadOnlyMemory<{element}>(buffer_{slot}, 0, count);"
        );
    }

    private static void EmitColumnCleanup(StringBuilder builder, PropertyModel prop, int slot)
    {
        ArrowLeafMapping map = ArrowMappingComponent.TryMap(prop)!;

        switch (map.Mode)
        {
            case ArrowExtractionMode.Direct when !prop.IsNullable:
                return;

            case ArrowExtractionMode.Utf8:
            {
                string element = prop.IsNullable
                    ? "global::System.ReadOnlyMemory<char>?"
                    : "global::System.ReadOnlyMemory<char>";
                builder.AppendLine($"            if (buffer_{slot} != null)");
                builder.AppendLine("            {");
                builder.AppendLine(
                    $"                global::System.Buffers.ArrayPool<{element}>.Shared.Return(buffer_{slot}, clearArray: true);"
                );
                builder.AppendLine("            }");
                builder.AppendLine($"            if (chars_{slot} != null)");
                builder.AppendLine("            {");
                builder.AppendLine(
                    $"                global::System.Buffers.ArrayPool<char>.Shared.Return(chars_{slot}, clearArray: false);"
                );
                builder.AppendLine("            }");
                return;
            }

            case ArrowExtractionMode.Binary:
            {
                string element = prop.IsNullable
                    ? "global::System.ReadOnlyMemory<byte>?"
                    : "global::System.ReadOnlyMemory<byte>";
                builder.AppendLine($"            if (buffer_{slot} != null)");
                builder.AppendLine("            {");
                builder.AppendLine(
                    $"                global::System.Buffers.ArrayPool<{element}>.Shared.Return(buffer_{slot}, clearArray: true);"
                );
                builder.AppendLine("            }");
                return;
            }

            case ArrowExtractionMode.Convert when !prop.IsNullable:
                builder.AppendLine($"            if (buffer_{slot} != null)");
                builder.AppendLine("            {");
                builder.AppendLine(
                    $"                global::System.Buffers.ArrayPool<{map.ParquetElementType}>.Shared.Return(buffer_{slot}, clearArray: false);"
                );
                builder.AppendLine("            }");
                return;

            default:
                builder.AppendLine($"            if (packed_{slot} != null)");
                builder.AppendLine("            {");
                builder.AppendLine(
                    $"                global::System.Buffers.ArrayPool<{map.ParquetElementType}>.Shared.Return(packed_{slot}, clearArray: false);"
                );
                builder.AppendLine("            }");
                builder.AppendLine($"            if (defLevels_{slot} != null)");
                builder.AppendLine("            {");
                builder.AppendLine(
                    $"                global::System.Buffers.ArrayPool<int>.Shared.Return(defLevels_{slot}, clearArray: false);"
                );
                builder.AppendLine("            }");
                return;
        }
    }

